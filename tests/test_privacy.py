"""Обезличивание вопроса и кода сессии."""
from __future__ import annotations

import pytest

from curator.privacy import redact, user_hash

KEEP = ("support@academy-data.example",)


@pytest.mark.parametrize("text, removed, placeholder", [
    ("пишите на ivan.petrov@mail.example", "ivan.petrov@mail.example", "[почта]"),
    ("мой номер +7 (916) 123-45-67", "123-45-67", "[номер]"),
    ("звоните 8.916.123.45.67", "8.916.123.45.67", "[номер]"),
    ("тг @ivan_petrov", "@ivan_petrov", "[ник]"),
    ("https://t.me/ivan_petrov", "ivan_petrov", "[ник]"),
    ("паспорт 4510 123456", "4510 123456", "[документ]"),
    ("Меня зовут Иван Петров, когда дедлайн?", "Иван Петров", "[имя]"),
    ("моё имя Мария", "Мария", "[имя]"),
    # Со строчной буквы — в чате так пишут часто.
    ("меня зовут иван петров, когда дедлайн?", "иван петров", "[имя]"),
    ("меня зовут иван и я не понимаю циклы", "иван", "[имя]"),
    ("МЕНЯ ЗОВУТ Олег, вопрос про hw2", "Олег", "[имя]"),
    # Мобильный номер внутри кода: длинные числа в коде не трогаем, а телефон — вырезаем.
    ("Меня зовут Иван, мой номер `+7 900 123-45-67`", "123-45-67", "[номер]"),
    ("```\nтелефон для связи 89001234567\n```", "89001234567", "[номер]"),
    ("```python\nphone = '8 (912) 345-67-89'\n```", "345-67-89", "[номер]"),
    # Паспорт со словом «серия» — с цифрами паспорта; ник в скобках и после двоеточия — ник.
    ("серия 4510 номер 123456", "4510", "[документ]"),
    ("серия 45 10 № 123456", "123456", "[документ]"),
    ("пишите мне (@ivan_petrov)", "@ivan_petrov", "[ник]"),
    ("мой ник: @ivan_petrov", "@ivan_petrov", "[ник]"),
    # Телефон рядом с датой ISO — всё равно номер; номер карты без разрядов перед «руб» — тоже.
    ("с 2026-11-01 звоните 89161234567", "89161234567", "[номер]"),
    ("перевёл 4276123456789012 руб", "4276123456789012", "[номер]"),
])
def test_contacts_removed(text: str, removed: str, placeholder: str):
    out = redact(text, keep=KEEP)
    assert removed not in out and placeholder in out


@pytest.mark.parametrize("text", [
    "Дедлайн 15.11.2026 23:59",
    "Почему 0.1 + 0.2 = 0.30000000000000004?",
    "в таблице 1 500 000 строк",
    "курс идёт 2026-2027",
    "ошибка в `orders = [1001 1002 1003 1004]`",
    "```python\nprint(12345678901)\n```",
    "Писал в support@academy-data.example, ответа нет",
    "меня зовут не помню как",  # первое слово служебное — это не имя
    "```python\nprint(12345678901)\nids = [79001234567890]\n```",  # не телефон: другая длина
    # Код и данные без обратных кавычек (замечание ревью: модель получала испорченный вопрос).
    "Почему pd.to_datetime('2026-11-12') возвращает NaT?",
    "Как отфильтровать заказы с 2026-11-01 по 2026-11-15?",
    "df[df.date > \"2026-11-01\"] пустой, хотя даты есть",
    "Столбец 2026-11-12 14:00 не парсится",
    "В датасете 1200000 строк, groupby работает долго",
    "Почему orders.query(\"qty >= @limit\") пишет UndefinedVariableError?",
    "df.query(\"city in @cities\") не находит переменную",
    "Серия из 1000 строк, 250 пропусков — как заполнить?",
])
def test_course_text_and_code_kept(text: str):
    assert redact(text, keep=KEEP) == text


def test_user_hash_is_stable_salted_and_not_reversible():
    a = user_hash("salt", "session-1")
    assert a == user_hash("salt", "session-1") and len(a) == 16
    assert a != user_hash("other", "session-1")
    assert "session" not in a
    assert user_hash("salt", "") == ""


def test_lowercase_name_keeps_rest_of_question():
    assert redact("меня зовут иван петров когда дедлайн hw1?") == "меня зовут [имя] когда дедлайн hw1?"
    # У имени с заглавной фамилия тоже ожидается с заглавной: «петров» после «Иван» — уже не часть имени.
    assert redact("Меня зовут Иван петров") == "Меня зовут [имя] петров"
